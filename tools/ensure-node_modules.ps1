param(
  [string]$RepoRoot
)

$ErrorActionPreference = 'Stop'

if (-not $RepoRoot) {
  $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
}

$nm = Join-Path $RepoRoot 'node_modules'
$offlineDir = Join-Path $RepoRoot 'tools\offline'
$vendorZip = Join-Path $offlineDir 'node_modules.zip'

if (Test-Path (Join-Path $nm 'pkg')) {
  Write-Host "node_modules already present"
  exit 0
}

if (-not (Test-Path $vendorZip)) {
  throw "node_modules missing and vendor zip not found. Create $vendorZip (zip of repo root node_modules)."
}

Write-Host "Extracting node_modules from $vendorZip ..."
if (Test-Path $nm) { Remove-Item -Recurse -Force $nm }
Expand-Archive -Path $vendorZip -DestinationPath $RepoRoot -Force

if (-not (Test-Path (Join-Path $nm 'pkg'))) {
  throw "Extraction finished but node_modules/pkg not found. Ensure node_modules.zip contains a top-level node_modules folder."
}

Write-Host "node_modules ready"
